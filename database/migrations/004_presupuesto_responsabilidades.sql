CREATE TABLE IF NOT EXISTS presupuesto_responsabilidades (
  id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  unidad_responsable VARCHAR(10) NOT NULL,
  actividad VARCHAR(10) NOT NULL,
  unidad_propietaria VARCHAR(10) NOT NULL,
  cuenta VARCHAR(20) NOT NULL,
  clasificacion ENUM('PROPIA_ADMINISTRADA','EXTERNA_ADMINISTRADA','PROPIA_NO_ADMINISTRADA','EXCLUIDA') NOT NULL,
  observacion VARCHAR(300) NULL,
  actualizado_en DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  UNIQUE KEY uq_responsabilidad (unidad_responsable, actividad, unidad_propietaria, cuenta),
  INDEX idx_responsable (unidad_responsable, clasificacion)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

